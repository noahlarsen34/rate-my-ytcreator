create table if not exists public.user_search_history (
  search_id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(user_id) on delete cascade,
  search text not null check (length(search) between 2 and 200),
  searched_at timestamptz not null default now()
);

create index if not exists user_search_history_user_time_idx
  on public.user_search_history (user_id, searched_at desc);

alter table public.user_search_history enable row level security;

revoke all on table public.user_search_history from public, anon, authenticated;
grant select on table public.user_search_history to authenticated;

drop policy if exists "Users can view their own search history" on public.user_search_history;
create policy "Users can view their own search history"
  on public.user_search_history
  for select
  to authenticated
  using (auth.uid() = user_id);

create or replace function public.record_user_search(p_search text)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_query text := left(regexp_replace(trim(coalesce(p_search, '')), '\s+', ' ', 'g'), 200);
  v_count bigint;
begin
  if v_user_id is null then
    raise exception 'Sign in to record search history.' using errcode = '28000';
  end if;

  if length(v_query) < 2 then
    raise exception 'Search must contain at least 2 characters.' using errcode = '22023';
  end if;

  insert into public.user_search_history (user_id, search)
  values (v_user_id, v_query);

  select count(*) into v_count
  from public.user_search_history
  where user_id = v_user_id;

  return v_count;
end;
$$;

revoke all on function public.record_user_search(text) from public, anon;
grant execute on function public.record_user_search(text) to authenticated;
